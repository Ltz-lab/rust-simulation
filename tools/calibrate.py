#!/usr/bin/env python3
"""Fit per-source damage multipliers and crit offsets to observations.

  python3 tools/calibrate.py <spec.toml> <observations.json> <out_calibration.toml> [--derived derived.toml] [--engine path] [-n iters]

Only damage *per hit* is fitted (a residual multiplier standing in for
talents/auras we don't model individually, plus a crit-chance offset).
With --derived (from tools/effects.py), the multipliers and buff modifiers
read from the game data go into the file first and the residual is fitted
on top of them.
Hit counts are never touched — those must come out of the engine's own
mechanics and rotation, which is what makes the result a real test.
"""
import argparse
import json
import os
import subprocess
import tempfile
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ENGINE = os.path.join(HERE, "..", "target", "release", "azsim")


def run(engine, spec, calib, n):
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as f:
        out = f.name
    cmd = [engine, spec, "-n", str(n), "--json", out, "--calib", calib]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
    res = json.load(open(out))
    os.unlink(out)
    return res


def write(path, cal, derived):
    srcs = derived.get("sources", {})
    with open(path, "w") as f:
        f.write("# Generated by tools/calibrate.py. Per source: `derived` is read from the\n")
        f.write("# game's spell modifiers (tools/effects.py); `mult` and `crit_bonus` are the\n")
        f.write("# residual fitted to observed logs on top. Hit counts are NOT fitted.\n\n")
        for name in sorted(set(cal) | set(srcs)):
            m, c = cal.get(name, (1.0, 0.0))
            f.write(f'[sources."{name}"]\n')
            if name in srcs:
                f.write(f'derived = {srcs[name]["derived"]:.6f}\n')
            f.write(f'mult = {m:.6f}\ncrit_bonus = {c:+.6f}\n\n')
        for b, patch in sorted(derived.get("buffs", {}).items()):
            for field, vals in sorted(patch.items()):
                f.write(f'[buffs."{b}".{field}]\n')
                for k, v in sorted(vals.items()):
                    f.write(f'"{k}" = {v:.4f}\n')
                f.write("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("observations")
    ap.add_argument("out")
    ap.add_argument("--engine", default=DEFAULT_ENGINE)
    ap.add_argument("-n", type=int, default=5000)
    ap.add_argument("--rounds", type=int, default=4)
    ap.add_argument("--derived")
    a = ap.parse_args()
    derived = tomllib.load(open(a.derived, "rb")) if a.derived else {}

    obs = json.load(open(a.observations))
    length = obs["fight_length"]
    write(a.out, {}, derived)
    res = run(a.engine, a.spec, a.out, a.n)
    mine = {s["name"] for s in res["sources"] if s["hits_per_fight"] > 0}
    targets = {}
    for name, o in obs["sources"].items():
        # a spell with both a direct hit and ticks (one result row) counts both
        # Some debuffs (e.g. Haunt) report zero-damage periodic callbacks
        # alongside their actual hit. Those are not damage hits to calibrate.
        ticks = o["ticks"] if o["tick_noncrit_avg"] > 0 else 0
        hits = o["direct_hits"] + ticks
        if name in mine and hits > 0:
            crit = (o["direct_crit_rate"] * o["direct_hits"] + o["tick_crit_rate"] * ticks) / hits
            targets[name] = (o["dps"] * length / hits, crit)
    missing = [n for n in obs["sources"] if n not in targets]

    cal = {n: (1.0, 0.0) for n in targets}
    for r in range(a.rounds):
        ours = {s["name"]: s for s in res["sources"]}
        worst = 0.0
        for n, (avg_t, crit_t) in targets.items():
            s = ours[n]
            m, c = cal[n]
            c_new = c + (crit_t - s["crit_rate"])
            # remove our crit effect, apply the target's, then match damage per hit
            m_new = m * avg_t / s["avg_hit"] if s["avg_hit"] > 0 else m
            cal[n] = (m_new, c_new)
            worst = max(worst, abs(avg_t / s["avg_hit"] - 1) if s["avg_hit"] else 0)
        write(a.out, cal, derived)
        res = run(a.engine, a.spec, a.out, a.n)
        print(f"round {r + 1}: worst per-hit error before update {worst * 100:.2f}%  ->  dps {res['dps']:.0f} (target {obs['dps']:.0f})")
    if missing:
        print("not modelled (no matching source in spec):", ", ".join(missing))


if __name__ == "__main__":
    main()
