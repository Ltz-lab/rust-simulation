#!/usr/bin/env python3
"""Write an overlay's [[rotation]] straight from a SimC profile's default action list.

  python3 tools/simc_overlay.py profiles/MID2_Demon_Hunter_Havoc.simc overlay/havoc_fel_scarred.toml

Every `actions=` / `actions+=/` line of the default list becomes one rule (or several, see
ALIASES), in SimC's order, with SimC's condition translated to the overlay's names. The rules
go between the `# >>> simc` and `# <<< simc` lines of the overlay file; everything else there
(spells, auras, talents, markers) is hand-written and says where the names come from.
Talent checks stay as `talent.X` and are read live from the player's passive auras.

Lines whose action the overlay has no spell for are kept as comments, as are action lists
other than the default one (items, potions).
"""
import re
import sys
import tomllib

# SimC actions that are not buttons the overlay suggests
SKIP = {"auto_attack", "retarget_auto_attack", "call_action_list", "pick_up_fragment", "snapshot_stats", "variable"}

# One SimC action is two buttons in the overlay: the form outside and inside Metamorphosis
# (SimC's immolation_aura casts Consuming Fire in Metamorphosis).
ALIASES = {"immolation_aura": ["consuming_fire", "immolation_aura"]}

# action.X.demonsurge_available -> the overlay's marker for that button
DEMONSURGE = {"immolation_aura": "consuming_fire", "eye_beam": "abyssal_gaze"}


def actions(profile):
    """(line number, action, options) for the default list, and its precombat variables."""
    out, variables = [], {}
    for n, line in enumerate(open(profile, encoding="utf-8"), 1):
        line = line.strip()
        m = re.match(r"actions(\.precombat)?(\+?=)/?(.*)$", line)
        if not m:
            continue
        name, *opts = m.group(3).split(",")
        kv = {}
        for o in opts:
            if "=" in o:
                k, v = o.split("=", 1)
                kv[k] = v
        if m.group(1):  # precombat: only its variable defaults matter here
            if name == "variable" and "default" in kv:
                variables[kv["name"]] = kv["default"]
            continue
        out.append((n, name, kv, line))
    return out, variables


def translate(cond, action, known, variables):
    auras, cooldowns, talents = known
    c = cond
    # (a>?b) is SimC's max
    c = re.sub(r"\(([\w.]+)>\?([\w.]+)\)", r"((\1)*((\1)>(\2))+(\2)*((\1)<=(\2)))", c)
    c = re.sub(r"action\.(\w+)\.demonsurge_available",
               lambda m: f"buff.demonsurge_{DEMONSURGE.get(m.group(1), m.group(1))}.up", c)
    c = re.sub(r"\b(buff|debuff)\.(\w+)\.down\b", r"!\1.\2.up", c)
    c = c.replace("gcd.max", "gcd").replace("hero_tree.felscarred", "talent.felscarred")
    c = re.sub(r"variable\.(\w+)", lambda m: variables.get(m.group(1), "0"), c)
    # SimC's bare charges / full_recharge_time are the action's own
    c = re.sub(r"(?<![.\w])(charges|full_recharge_time)\b", rf"cooldown.{action}.\1", c)
    # auras and debuffs of talents or hero trees the overlay doesn't track are never up
    def aura(m):
        return m.group(0) if m.group(2) in auras else "0"
    c = re.sub(r"\b(buff|debuff)\.(\w+)\.(up|remains|stack)\b", aura, c)
    c = re.sub(r"\bactive_dot\.\w+", "0", c)
    missing = [t for t in re.findall(r"\btalent\.(\w+)", c) if t not in talents]
    missing += [cd for cd in re.findall(r"\bcooldown\.(\w+)\.", c) if cd not in cooldowns]
    return c, missing


def main():
    profile, overlay = sys.argv[1], sys.argv[2]
    text = open(overlay, encoding="utf-8").read()
    spec = tomllib.loads(text)
    spells = {s["name"] for s in spec["spells"]}
    groups = spells | {s["group"] for s in spec["spells"] if "group" in s}
    auras = {a["name"] for a in spec.get("auras", [])} | {m["name"] for m in spec.get("markers", [])}
    talents = {t["name"] for t in spec.get("talents", [])}
    acts, variables = actions(profile)
    out, problems = [], []
    for n, name, kv, line in acts:
        if name in SKIP:
            continue
        cond = kv.get("if", "")
        buttons = [b for b in ALIASES.get(name, [name]) if b in spells]
        if not buttons:
            out.append(f"# [simc line {n}] no button for '{name}': {line}\n")
            continue
        out.append(f"# [simc line {n}] {line}\n")
        for b in buttons:
            c, missing = translate(cond, name, (auras, groups, talents), variables)
            problems += [f"line {n}: '{x}' not in {overlay}" for x in missing]
            out.append(f'[[rotation]]\naction = "{b}"\n' + (f'if = "{c}"\n' if c else "") + "\n")
    if problems:
        sys.exit("\n".join(sorted(set(problems))))
    start, end = text.index("# >>> simc\n"), text.index("# <<< simc")
    body = f"# Generated by tools/simc_overlay.py from {profile}; edit there, not here.\n\n" + "".join(out)
    open(overlay, "w", encoding="utf-8").write(text[: start + len("# >>> simc\n")] + body + text[end:])
    print(f"{sum(1 for o in out if o.startswith('[['))} rules from {len(acts)} action lines")


if __name__ == "__main__":
    main()
